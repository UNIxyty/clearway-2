-- Role permissions (portal foundations: "let admins decide who can do what"). docs/permissions.md explains the rules.
--
-- Code (lib/permissions/catalogue.mjs) lists every action; these tables say which role may do which. Read and written
-- by the services with the service role only: no client policy exists, so the anon key and user sessions see nothing.
-- Run this whole file once, BEFORE deploying the services that read it (they fail closed: no table, no writes).
-- Safe to re-run: the seed never overwrites a decision already made.

create table if not exists public.permission_grants (
  role text not null,
  action text not null,
  allowed boolean not null default false,
  updated_at timestamptz not null default now(),
  updated_by uuid null,
  updated_by_email text null,
  primary key (role, action)
);

-- Every change, forever: who, when, which action, which role, on or off.
create table if not exists public.permission_changes (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  actor_id uuid null,
  actor_email text null,
  role text not null,
  action text not null,
  allowed boolean not null,
  previous boolean null,
  via text not null default 'screen'
);
create index if not exists permission_changes_at_idx on public.permission_changes (at desc);

alter table public.permission_grants enable row level security;
alter table public.permission_changes enable row level security;
revoke all on public.permission_grants from anon, authenticated;
revoke all on public.permission_changes from anon, authenticated;

-- The history is append-only: not even the service role edits or deletes a row.
create or replace function public.permission_changes_append_only() returns trigger language plpgsql as $$
begin
  raise exception 'permission_changes rows are never changed or deleted' using errcode = '42501';
end $$;
drop trigger if exists permission_changes_append_only on public.permission_changes;
create trigger permission_changes_append_only before update or delete on public.permission_changes
  for each row execute function public.permission_changes_append_only();

-- The only way grants change: applies a batch and logs each real change in the same transaction. Also refuses, here in
-- the database, the two lock-outs (the developer role's "manage permissions"; nobody left holding it). The "not your
-- own" rule needs the person's role and is checked by the API before calling this.
create or replace function public.permission_apply(p_changes jsonb, p_actor_id uuid, p_actor_email text, p_via text)
returns integer language plpgsql security definer set search_path = public as $$
declare
  c jsonb; prev boolean; next boolean; n integer := 0;
begin
  for c in select * from jsonb_array_elements(p_changes) loop
    next := (c->>'allowed')::boolean;
    if (c->>'role') = 'developer' and (c->>'action') = 'permissions.manage' and not next then
      raise exception 'Manage permissions cannot be taken from the developer role.' using errcode = '42501';
    end if;
    select g.allowed into prev from permission_grants g where g.role = c->>'role' and g.action = c->>'action' for update;
    if prev is distinct from next then
      insert into permission_grants (role, action, allowed, updated_at, updated_by, updated_by_email)
        values (c->>'role', c->>'action', next, now(), p_actor_id, p_actor_email)
        on conflict (role, action) do update
          set allowed = excluded.allowed, updated_at = now(), updated_by = excluded.updated_by, updated_by_email = excluded.updated_by_email;
      insert into permission_changes (actor_id, actor_email, role, action, allowed, previous, via)
        values (p_actor_id, p_actor_email, c->>'role', c->>'action', next, prev, coalesce(p_via, 'screen'));
      n := n + 1;
    end if;
  end loop;
  if not exists (select 1 from permission_grants where action = 'permissions.manage' and allowed) then
    raise exception 'At least one role must keep Manage permissions.' using errcode = '42501';
  end if;
  return n;
end $$;
revoke all on function public.permission_apply(jsonb, uuid, text, text) from public, anon, authenticated;
grant execute on function public.permission_apply(jsonb, uuid, text, text) to service_role;

