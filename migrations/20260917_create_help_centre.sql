-- Service-role only: RLS on, no policies.
alter table public.help_threads enable row level security;
alter table public.help_messages enable row level security;
alter table public.help_events enable row level security;
alter table public.help_attachments enable row level security;
alter table public.help_saved_replies enable row level security;
