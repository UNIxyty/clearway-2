// Read-only copy of production's reference data into the rig's local database, so the portal's lookups
// (airports, AIP documents, links…) work. Reads production ONLY when a person types the phrase; never
// copies agent_* tables, auth, or user data; never writes to production. Schema comes from PostgREST's
// OpenAPI description (types + primary keys), created locally as plain tables; rows are copied in pages.
import fs from "node:fs"; import path from "node:path";
const PHRASE = "yes, read production to seed the rig";
if (process.env.RIG_ALLOW_PRODUCTION_READ !== PHRASE) { console.error(`Refusing: set RIG_ALLOW_PRODUCTION_READ="${PHRASE}"`); process.exit(2); }
const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const load = (f) => Object.fromEntries(fs.readFileSync(path.join(root, f), "utf8").split("\n").filter((l) => /^[A-Z_]+=/.test(l)).map((l) => { const i = l.indexOf("="); return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")]; }));
const prod = load(process.env.RIG_SOURCE_ENV || ".env"), rig = load(".env.rig");
if (!/127\.0\.0\.1|localhost/.test(rig.NEXT_PUBLIC_SUPABASE_URL)) { console.error("refusing: .env.rig is not a local Supabase"); process.exit(78); }
if (/127\.0\.0\.1|localhost/.test(prod.NEXT_PUBLIC_SUPABASE_URL)) { console.error("refusing: the source env is not production"); process.exit(2); }
const P = { url: prod.NEXT_PUBLIC_SUPABASE_URL.replace(/\/+$/, ""), key: prod.SUPABASE_SERVICE_ROLE_KEY };
const R = { url: rig.NEXT_PUBLIC_SUPABASE_URL.replace(/\/+$/, ""), key: rig.SUPABASE_SERVICE_ROLE_KEY };
const hdr = (k) => ({ apikey: k, authorization: `Bearer ${k}` });
const SKIP = /^(agent_|pickem|playoff|auth|storage|help_|debug_|telegram|email_|user_|search_events|profiles?$)/;  // never agent data, never people, never their activity
const MAX_ROWS = Number(process.env.RIG_SEED_MAX_ROWS || 5000);
const spec = await (await fetch(`${P.url}/rest/v1/`, { headers: hdr(P.key) })).json();
const defs = spec.definitions ?? {};
const pgType = (prop) => { const f = String(prop.format || ""); if (/\[\]$/.test(f)) return f; if (/^(uuid|jsonb|json|text|integer|bigint|boolean|date|numeric|real|smallint)$/.test(f)) return f; if (/^timestamp/.test(f)) return "timestamptz"; if (/^time/.test(f)) return "time"; if (/character varying|^varchar/.test(f)) return "text"; if (/double precision/.test(f)) return "double precision"; if (f === "ARRAY" || prop.type === "array") return "jsonb"; if (prop.type === "integer") return "bigint"; if (prop.type === "number") return "double precision"; if (prop.type === "boolean") return "boolean"; if (prop.type === "object") return "jsonb"; return "text"; };
const tables = Object.keys(defs).filter((t) => !SKIP.test(t)).sort();
const local = (async () => { const s = await (await fetch(`${R.url}/rest/v1/`, { headers: hdr(R.key) })).json(); return s.definitions ?? {}; })();
const sql = [];
for (const t of tables) {
  const d = defs[t]; const props = d.properties ?? {};
  const pk = Object.entries(props).filter(([, p]) => /<pk\/>/.test(String(p.description || ""))).map(([c]) => c);
  const cols = Object.entries(props).map(([c, p]) => `"${c}" ${pgType(p)}`);
  const have = (await local)[t];
  if (!have) sql.push(`create table if not exists public."${t}" (${cols.join(", ")}${pk.length ? `, primary key (${pk.map((c) => `"${c}"`).join(", ")})` : ""});`);
  else for (const [c, p] of Object.entries(props)) if (!have.properties?.[c]) sql.push(`alter table public."${t}" add column if not exists "${c}" ${pgType(p)};`);
}
const migration = path.join(root, "rig/supabase/migrations/0100_cloned_reference_schema.sql");
fs.writeFileSync(migration, `-- Generated by rig/seed-from-production.mjs from production's OpenAPI description (${new Date().toISOString().slice(0, 10)}). Reference tables only.\n${sql.join("\n")}\n`);
console.log(`schema: ${tables.length} tables, ${sql.length} statements → ${path.relative(root, migration)}`);
console.log("apply it with: rig/db.sh reset   (then re-run this script with RIG_SEED_DATA=1 to copy rows)");
if (process.env.RIG_SEED_DATA !== "1") process.exit(0);
for (const t of tables) {
  let copied = 0, offset = 0;
  for (;;) {
    const r = await fetch(`${P.url}/rest/v1/${t}?select=*&limit=1000&offset=${offset}`, { headers: hdr(P.key) });
    if (!r.ok) { console.log(`${t}: read ${r.status}`); break; }
    const rows = await r.json(); if (!rows.length) break;
    const w = await fetch(`${R.url}/rest/v1/${t}`, { method: "POST", headers: { ...hdr(R.key), "content-type": "application/json", prefer: "resolution=ignore-duplicates,return=minimal" }, body: JSON.stringify(rows) });
    if (!w.ok) { console.log(`${t}: write ${w.status} ${(await w.text()).slice(0, 120)}`); break; }
    copied += rows.length; offset += rows.length;
    if (rows.length < 1000 || copied >= MAX_ROWS) break;
  }
  if (copied) console.log(`${t}: ${copied} rows`);
}
console.log("done");
